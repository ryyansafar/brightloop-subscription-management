// --size=N (or SEED_SIZE) controls how many subscriptions to create (default 1500, full demo 3000).
// Invoices come from the real billing engine, so numbers match what the app computes.
import { PrismaClient } from "@prisma/client";
import { fakerEN_IN as faker } from "@faker-js/faker";
import { runBilling } from "../src/lib/billing";
import { addDays, startOfDayUTC } from "../src/lib/dates";
import { seedCatalog } from "./seed/catalog";
import { DEMO_LOGINS, DEMO_PASSWORD, seedPeople } from "./seed/people";
import { settleInvoices } from "./seed/ledger";
import { generateSubscriptions } from "./seed/subscriptions";
import { wipeAll } from "./seed/wipe";

const db = new PrismaClient();
const log = (message: string) => process.stdout.write(`${message}\n`);

const CLOSE_REASONS = ["Switched provider", "Budget cuts", "Merged into parent account", "Project ended"];

async function main(): Promise<void> {
  if (process.env.NODE_ENV === "production") throw new Error("Refusing to seed in production");
  const sizeArg = process.argv.find((a) => a.startsWith("--size="))?.split("=")[1];
  const size = Math.max(10, Number(sizeArg ?? process.env.SEED_SIZE) || 1500);
  const customerCount = Math.max(5, Math.ceil(size / 7));
  const now = startOfDayUTC(new Date());
  const started = Date.now();
  faker.seed(2026);

  await wipeAll(db);
  await seedPeople(db, customerCount);
  const catalog = await seedCatalog(db);
  const { pausedIds, churnIds } = await generateSubscriptions(db, catalog, size, customerCount, now);
  log(`Created ${size} subscriptions for ${customerCount} customers`);

  // Phase 1: bill up to 20 days ago, then pause some, so paused periods are never billed.
  const phaseOne = await runBilling(addDays(now, -20), db);
  if (pausedIds.length > 0) {
    await db.subscription.updateMany({
      where: { id: { in: pausedIds }, status: "ACTIVE" },
      data: { status: "PAUSED", pausedAt: addDays(now, -20) },
    });
  }
  // Phase 2: bill up to today.
  const phaseTwo = await runBilling(now, db);

  // Churned subscriptions stopped billing at their end date; close them for real.
  for (const id of churnIds) {
    await db.subscription.updateMany({
      where: { id, status: "ACTIVE", nextInvoiceDate: null },
      data: { status: "CLOSED", closeReason: faker.helpers.arrayElement(CLOSE_REASONS) },
    });
  }

  await settleInvoices(db, now);

  const errors = phaseOne.errors.length + phaseTwo.errors.length;
  const invoices = await db.invoice.count();
  log(`Invoices generated by the billing engine: ${invoices} (errors: ${errors})`);
  log(`Done in ${((Date.now() - started) / 1000).toFixed(1)}s`);
  log("Demo logins (password " + DEMO_PASSWORD + "): " + DEMO_LOGINS.map((u) => u.email).join(", "));
}

main()
  .catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
